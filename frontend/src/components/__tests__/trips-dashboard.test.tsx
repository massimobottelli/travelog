// Mock leaflet.heat plugin (used by HeatMap component)
vi.mock("leaflet.heat", () => ({}));

vi.mock("leaflet", () => {
  const state = h.state;

  class MapMock {
    zoom = 8;
    fitBounds = vi.fn();
    flyTo = vi.fn();
    /* HeatMap filters its points against the current viewport (§overview):
       it pads the bounds and tests each marker against them. */
    getBounds = () => ({
      pad: () => ({
        contains: ([lat, lng]: [number, number]) => lat >= 0 && lat <= 90 && lng >= 0 && lng <= 180,
      }),
    });
    closePopup = vi.fn();
    remove = vi.fn();
    addLayer = vi.fn();
    removeLayer = vi.fn();
    setView = vi.fn(() => this);
    getZoom = () => this.zoom;
    handlers: Record<string, (ev?: unknown) => void> = {};
    on(event: string, cb: (ev?: unknown) => void) {
      this.handlers[event] = cb;
      return this;
    }
    off(event: string) {
      delete this.handlers[event];
      return this;
    }
    constructor(_el: unknown) {
      void _el;
      state.mapCount += 1;
      state.maps.push(this);
    }
  }

  function makeMarker(latlng: unknown, opts: unknown) {
    const marker: any = {
      latlng,
      opts,
      popupOpen: false,
      handlers: {} as Record<string, () => void>,
      bindPopup: () => marker,
      on(event: string, cb: () => void) {
        marker.handlers[event] = cb;
        return marker;
      },
      openPopup() {
        marker.popupOpen = true;
        return marker;
      },
      closePopup() {
        marker.popupOpen = false;
        return marker;
      },
      getLatLng() {
        return marker.latlng;
      },
      /* Hover visual feedback swaps the icon (TripMap enlarge-on-hover). */
      setIcon(newIcon: unknown) {
        marker.opts = { ...marker.opts, icon: newIcon };
        return marker;
      },
    };
    state.markers.push(marker);
    return marker;
  }

  const chain = () => {
    const obj: any = {
      addTo: () => obj,
      remove: () => {},
      on: () => obj,
      addLayer: () => {},
      clearLayers: () => {},
    };
    return obj;
  };

  return {
    default: {
      map: (_el: unknown) => new MapMock(_el),
      tileLayer: () => chain(),
      layerGroup: () => chain(),
      marker: makeMarker,
      divIcon: (opts: unknown) => opts,
      polyline: () => chain(),
      latLngBounds: (latlngs: unknown) => ({ latlngs }),
      control: {
        layers: () => chain(),
        zoom: () => chain(),
      },
      /* HeatMap (overview) records its points: [lat, lng, intensity]. */
      heatLayer: (latlngs: unknown, opts: unknown) => {
        const layer: any = {
          latlngs,
          opts,
          addTo: () => layer,
          setLatLngs(next: unknown) {
            layer.latlngs = next;
            return layer;
          },
          setOptions(next: Record<string, unknown>) {
            layer.opts = { ...layer.opts, ...next };
            return layer;
          },
        };
        state.heatLayers.push(layer);
        return layer;
      },
      Control: class {
        onAdd: (() => HTMLElement) | null = null;
        constructor(_opts: unknown) {
          void _opts;
        }
        addTo() {
          this.onAdd?.();
          return this;
        }
      },
      DomUtil: {
        create: (tag: string, cls: string) => {
          const el = document.createElement(tag);
          el.className = cls;
          return el;
        },
      },
      DomEvent: {
        disableClickPropagation: vi.fn(),
        disableScrollPropagation: vi.fn(),
      },
    },
  };
});

